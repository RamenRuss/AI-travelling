def _refusal(kind):
    text = {
        "offtopic": ("Это не про поездки", "Я помогаю только с путешествиями и жизнью в Приморском крае. Могу спланировать маршрут, подсказать паромы или тропы."),
        "region": ("Это не Приморский край", "Я работаю только с Приморским краем. Давайте спланируем поездку сюда — например, на острова залива Петра Великого."),
        "jail": ("Остаюсь в своей роли", "Правила я менять не буду. Зато могу собрать план на выходные по Приморью — просто опишите, что хотите."),
    }[kind]
    return {"type": "refusal", "title": text[0], "text": text[1],
            "steps": ["Проверяю запрос на соответствие теме"], "meta": _meta(1, 210)}


def respond(message: str, transport: str = "any") -> dict:
    transport = transport if transport in TRANSPORT else "any"
    m = message.strip()
    if RE_JAIL.search(m):
        return _refusal("jail")
    if RE_REGION.search(m):
        return _refusal("region")
    if RE_OFFTOPIC.search(m) and not RE_PRIM.search(m):
        return _refusal("offtopic")
    if RE_GOV.search(m):
        return _info_gov()
    if RE_FOOD.search(m):
        return _info_food()
    if RE_PRIM.search(m):
        if RE_FERRY.search(m):
            plan = _plan_ferry(transport)
        elif RE_HIKE.search(m):
            plan = _plan_hike(transport)
        else:
            plan = _plan_route(transport)
        plan["type"] = "plan"
        plan["transport"] = transport
        plan["steps"] = STEPS_PLAN
        return plan
    return _refusal("offtopic")
