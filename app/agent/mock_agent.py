def _d(offset):
    today = date.today()
    sat = today + timedelta(days=(5 - today.weekday()) % 7 or 7)
    d = sat + timedelta(days=offset)
    return f"{WD[d.weekday()]}, {d.day} {MONTHS[d.month - 1]}"


